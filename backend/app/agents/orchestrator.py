"""AI Orchestrator — runs the full agent pipeline in order and assembles the final verdict."""
import uuid
from datetime import datetime, timezone

from app.agents import (
    intake_agent, detection_agent, forensic_agent,
    verification_agent, confidence_agent, explanation_agent, report_agent
)
from app.storage import save_analysis

DISCLAIMER = ("This is an AI-based authenticity assessment generated by DeepGuard AI. "
              "It is not absolute proof of an image's authenticity or manipulation. "
              "Always use human judgement for critical decisions.")

VERDICT_COLOR = {"LIKELY REAL": "green", "LIKELY FAKE": "red", "UNCERTAIN": "yellow"}


def run_pipeline(content: bytes, mime_type: str, filename: str) -> dict:
    analysis_id = uuid.uuid4().hex[:12]
    timestamp = datetime.now(timezone.utc).isoformat()
    agent_log = [{"agent": "AI Orchestrator", "status": "started", "detail": f"id={analysis_id}"}]

    # 1. Intake / Validation
    intake = intake_agent.run(content, mime_type, filename)
    agent_log.append(intake["log"])
    if not intake["ok"]:
        return _error_response(analysis_id, filename, timestamp, agent_log, intake["errors"])

    image_path = intake["path"]

    # 2. Detection
    detection_out = detection_agent.run(image_path)
    agent_log.append(detection_out["log"])
    if not detection_out["ok"]:
        return _error_response(analysis_id, filename, timestamp, agent_log, detection_out["errors"])
    detection = detection_out["result"]

    # 3. Forensic
    forensic_out = forensic_agent.run(image_path, mime_type)
    agent_log.append(forensic_out["log"])
    forensic = forensic_out["evidence"]

    # 4. Verification
    verification_out = verification_agent.run(detection, forensic)
    agent_log.append(verification_out["log"])
    verification = verification_out["verification"]

    # 5. Confidence
    confidence_out = confidence_agent.run(detection, verification)
    agent_log.append(confidence_out["log"])
    confidence = confidence_out["confidence"]

    # 6. Explanation
    explanation_out = explanation_agent.run(detection, forensic, verification, confidence)
    agent_log.append(explanation_out["log"])
    explanation = explanation_out["explanation"]

    verdict = verification["verdict"]
    agent_log.append({"agent": "AI Orchestrator", "status": "completed", "detail": f"verdict={verdict}"})

    analysis = {
        "id": analysis_id,
        "filename": filename,
        "timestamp": timestamp,
        "verdict": verdict,
        "verdict_color": VERDICT_COLOR.get(verdict, "yellow"),
        "detection": detection,
        "forensic": forensic,
        "verification": verification,
        "confidence": confidence,
        "explanation": explanation,
        "agent_log": agent_log,
        "disclaimer": DISCLAIMER,
        "error": None,
        "simulation_mode": detection.get("simulation_mode", False),
    }

    save_analysis(analysis)
    return analysis


def generate_report(analysis_id: str):
    from app.storage import get_analysis
    analysis = get_analysis(analysis_id)
    if not analysis:
        return None
    return report_agent.generate_pdf(analysis)


def _error_response(analysis_id, filename, timestamp, agent_log, errors):
    return {
        "id": analysis_id,
        "filename": filename,
        "timestamp": timestamp,
        "verdict": "ERROR",
        "verdict_color": "yellow",
        "detection": None,
        "forensic": None,
        "verification": None,
        "confidence": None,
        "explanation": None,
        "agent_log": agent_log,
        "disclaimer": DISCLAIMER,
        "error": "; ".join(errors),
    }
